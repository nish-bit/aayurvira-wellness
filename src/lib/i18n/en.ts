/**
 * Deeply widen the literal string types inferred from `en` (e.g. "Home")
 * to `string`, so `hi.ts` — which holds different literal text but must
 * match this same shape — type-checks against it correctly.
 */
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? Widen<U>[]
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T;

export type Dictionary = Widen<typeof en>;
